import type { Graph } from "@doodleforge/ir";
import { CloudConstraintSchema, CloudPropsSchema } from "./schema.js";

const resourceTypes = { service: "aws_ecs_service", database: "aws_db_instance", cache: "aws_elasticache_cluster", bucket: "aws_s3_bucket", security_group: "aws_security_group", queue: "aws_sqs_queue" } as const;

export function emitTerraform(graph: Graph) {
  const constraints = CloudConstraintSchema.parse({ provider: graph.constraints.provider ?? "aws", region: graph.constraints.region ?? "us-east-1", monthly_budget_usd: graph.constraints.monthly_budget_usd, compliance: graph.constraints.compliance ?? [] });
  if (constraints.provider !== "aws") throw new Error("Terraform templates currently support AWS resources only");
  const blocks = [
    'terraform {\n  required_providers {\n    aws = {\n      source  = "hashicorp/aws"\n      version = "~> 5.0"\n    }\n  }\n}',
    `provider "aws" {\n  region = ${hclString(constraints.region)}\n}`,
  ];
  const assumptions: string[] = [];
  const names = new Set<string>();
  const variables = new Set<string>();
  for (const node of graph.nodes.filter((item) => item.type in resourceTypes)) {
    const type = node.type as keyof typeof resourceTypes;
    const props = CloudPropsSchema.parse(node.props);
    const name = normalizeResourceName(props.resourceName ?? node.label);
    if (names.has(`${type}:${name}`)) throw new Error(`Duplicate cloud resource name '${name}' for ${type}`);
    names.add(`${type}:${name}`);
    const resource = resourceTypes[type];
    const common = [`  tags = ${hclMap({ Name: name, ...(props.tags ?? {}) })}`];
    if (type === "bucket") {
      blocks.push(`resource "${resource}" "${name}" {\n  bucket = ${hclString(name)}\n  force_destroy = false\n${common.join("\n")}\n}`);
      blocks.push(`resource "aws_s3_bucket_server_side_encryption_configuration" "${name}" {\n  bucket = aws_s3_bucket.${name}.id\n  rule {\n    apply_server_side_encryption_by_default {\n      sse_algorithm = "AES256"\n    }\n  }\n}`);
      if (props.public === true) assumptions.push(`${name}: diagram marks this bucket public; review the high-severity exposure finding before export.`);
    } else if (type === "security_group") {
      const ingress = (props.ingress ?? []).map((rule) => `  ingress {\n    from_port = ${rule.port}\n    to_port = ${rule.port}\n    protocol = "tcp"\n    cidr_blocks = [${hclString(rule.cidr)}]\n  }`).join("\n");
      blocks.push(`resource "${resource}" "${name}" {\n  name = ${hclString(name)}\n  description = "Generated by DoodleForge; review ingress rules before use"\n  vpc_id = var.vpc_id\n${ingress ? `${ingress}\n` : ""}${common.join("\n")}\n}`);
      if (!variables.has("vpc_id")) { blocks.push('variable "vpc_id" {\n  type = string\n  description = "Existing VPC ID"\n}'); variables.add("vpc_id"); }
    } else if (type === "queue") {
      blocks.push(`resource "${resource}" "${name}" {\n  name = ${hclString(name)}\n  sqs_managed_sse_enabled = true\n${common.join("\n")}\n}`);
    } else if (type === "cache") {
      blocks.push(`resource "${resource}" "${name}" {\n  name = ${hclString(name)}\n  engine = ${hclString(props.engine ?? "redis")}\n  node_type = ${hclString(props.instanceClass ?? "cache.t4g.micro")}\n  num_cache_nodes = 1\n  port = 6379\n${common.join("\n")}\n}`);
    } else if (type === "database") {
      const passwordVariable = `${name}_password`;
      if (!variables.has(passwordVariable)) { blocks.push(`variable "${passwordVariable}" {\n  type = string\n  sensitive = true\n  description = "Supply ${name} database password through a secret manager"\n}`); variables.add(passwordVariable); }
      blocks.push(`resource "${resource}" "${name}" {\n  identifier = ${hclString(name)}\n  engine = ${hclString(props.engine ?? "postgres")}\n  instance_class = ${hclString(props.instanceClass ?? "db.t4g.micro")}\n  allocated_storage = 20\n  username = "doodleforge"\n  password = var.${passwordVariable}\n  skip_final_snapshot = true\n  storage_encrypted = true\n${common.join("\n")}\n}`);
    } else {
      assumptions.push(`${name}: ECS cluster and task definition references must be supplied before plan validation.`);
      blocks.push(`resource "${resource}" "${name}" {\n  name = ${hclString(name)}\n  desired_count = 1\n  launch_type = "FARGATE"\n  cluster = var.cluster_arn\n  task_definition = var.task_definition_arn\n  network_configuration {\n    subnets = var.subnet_ids\n    assign_public_ip = false\n  }\n${common.join("\n")}\n}`);
      for (const [variable, type] of [["cluster_arn", "string"], ["task_definition_arn", "string"], ["subnet_ids", "list(string)"]] as const) {
        if (!variables.has(variable)) { blocks.push(`variable "${variable}" { type = ${type} }`); variables.add(variable); }
      }
    }
  }
  if (blocks.length === 2) throw new Error("Cloud diagram has no supported resource nodes");
  if (constraints.monthly_budget_usd) assumptions.push(`Monthly budget ${constraints.monthly_budget_usd} USD is recorded for review; these templates do not estimate cost.`);
  if (constraints.compliance.length) assumptions.push(`Compliance constraints: ${constraints.compliance.join(", ")}; verify these controls with your cloud security team.`);
  return { hcl: `${blocks.join("\n\n")}\n`, assumptions, mode: "plan-only" as const };
}

function hclString(value: string) { return JSON.stringify(value.replace(/[\r\n]/g, " ")); }
function hclMap(value: Record<string, string>) { return `{ ${Object.entries(value).map(([key, item]) => `${hclString(key)} = ${hclString(item)}`).join(", ")} }`; }
function normalizeResourceName(value: string) {
  const name = value.toLowerCase().replace(/[^a-z0-9_-]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 48);
  if (!name) throw new Error("Cloud resource names must include letters or digits");
  return name;
}
